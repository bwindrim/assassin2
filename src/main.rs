pub mod generator;
pub mod parser;
pub mod recogniser;
pub mod representation;
pub mod namelist;

use crate::recogniser::Recogniser;

fn main() {
    println!("Assassin 6809 assembler, V2.0");
    let mut namelist = namelist::Namelist::new();
    let mut recogniser = Recogniser::new(&mut namelist);
    if let Ok(program) = recogniser.parse("tst/boot.a") {
        println!("Recogniser: {:?}", recogniser);
        let bytes = generator::generate(program, &namelist);
        println!("Generated bytes: {:#02x?}", bytes);
    }
    println!("Namelist: {:?}", namelist);
    println!("Done");
}
