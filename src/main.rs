pub mod generator;
pub mod parser;
pub mod recogniser;
pub mod representation;

use crate::recogniser::Recogniser;

fn main() {
    println!("Assassin 6809 assembler, V2.0");
    let mut recogniser = Recogniser::new();
    if let Ok(program) = recogniser.parse("tst/boot.a") {
        let bytes = generator::generate(program);
        println!("Generated bytes: {:#02x?}", bytes);
    }
    println!("Namelist: {:?}", recogniser);
    println!("Done");
}
